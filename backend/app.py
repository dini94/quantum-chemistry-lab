"""Optional local RDKit + ASE service for Quantum Chemistry Lab Module 01.
Run: uvicorn app:app --host 127.0.0.1 --port 8765
"""
from __future__ import annotations
from io import BytesIO
from pathlib import Path
import tempfile, zipfile
from typing import Literal
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from rdkit import Chem
from rdkit.Chem import AllChem, rdMolDescriptors
from ase import Atoms
from ase.io import write

app = FastAPI(title="Quantum Chemistry Lab Local RDKit/ASE", version="0.1.0")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_credentials=False, allow_methods=["*"], allow_headers=["*"])
class BuildRequest(BaseModel):
    smiles: str = Field(min_length=1, max_length=5000)
    force_field: Literal["MMFF94", "UFF"] = "MMFF94"
    add_hydrogens: bool = True
    seed: int = 20261022
    max_iterations: int = Field(default=1000, ge=1, le=10000)

def build(req: BuildRequest):
    mol = Chem.MolFromSmiles(req.smiles)
    if mol is None:
        raise HTTPException(422, "RDKit could not parse this SMILES. Check syntax, valence, ring closures and charge.")
    if req.add_hydrogens:
        mol = Chem.AddHs(mol)
    status = AllChem.EmbedMolecule(mol, randomSeed=req.seed)
    if status != 0:
        raise HTTPException(422, "3D conformer generation failed. Try a different conformer seed or inspect the structure.")
    ff_name = req.force_field
    if ff_name == "MMFF94" and AllChem.MMFFHasAllMoleculeParams(mol):
        props = AllChem.MMFFGetMoleculeProperties(mol)
        ff = AllChem.MMFFGetMoleculeForceField(mol, props)
    else:
        if ff_name == "MMFF94": ff_name = "UFF (MMFF parameters unavailable)"
        if not AllChem.UFFHasAllMoleculeParams(mol):
            raise HTTPException(422, "Neither selected MMFF parameters nor UFF parameters are available for this molecule.")
        ff = AllChem.UFFGetMoleculeForceField(mol)
    e0 = float(ff.CalcEnergy())
    if ff_name.startswith("UFF"):
        opt_status = AllChem.UFFOptimizeMolecule(mol, maxIters=req.max_iterations)
        ff2 = AllChem.UFFGetMoleculeForceField(mol)
    else:
        opt_status = AllChem.MMFFOptimizeMolecule(mol, maxIters=req.max_iterations)
        ff2 = AllChem.MMFFGetMoleculeForceField(mol, AllChem.MMFFGetMoleculeProperties(mol))
    energy = float(ff2.CalcEnergy())
    conf = mol.GetConformer()
    symbols = [a.GetSymbol() for a in mol.GetAtoms()]
    coords = [[conf.GetAtomPosition(i).x, conf.GetAtomPosition(i).y, conf.GetAtomPosition(i).z] for i in range(mol.GetNumAtoms())]
    xyz = f"{len(symbols)}\nGenerated by RDKit; {ff_name} optimization status={opt_status}\n" + "\n".join(f"{s:2s} {x:.8f} {y:.8f} {z:.8f}" for s,(x,y,z) in zip(symbols, coords)) + "\n"
    return {"mol": mol, "symbols": symbols, "coords": coords, "xyz": xyz, "formula": rdMolDescriptors.CalcMolFormula(mol), "atom_count": len(symbols), "force_field": ff_name, "energy_before_kcal_mol": e0, "energy_kcal_mol": energy, "optimizer_status": int(opt_status), "smiles": Chem.MolToSmiles(Chem.RemoveHs(mol))}

@app.get("/api/health")
def health(): return {"ok": True, "service": "RDKit + ASE", "rdkit": Chem.rdBase.rdkitVersion}

@app.post("/api/optimize")
def optimize(req: BuildRequest):
    r = build(req)
    return {k:v for k,v in r.items() if k != "mol"}

@app.post("/api/export")
def export(req: BuildRequest):
    r = build(req)
    atoms = Atoms(symbols=r["symbols"], positions=r["coords"], pbc=False)
    atoms.info["smiles"] = req.smiles
    atoms.info["optimization_method"] = r["force_field"]
    with tempfile.TemporaryDirectory() as tmp:
        d = Path(tmp)
        write(d/"molecule.xyz", atoms)
        write(d/"molecule.pdb", atoms)
        # CIF is a padded P1 molecular box, not a predicted crystal structure.
        span = atoms.positions.max(axis=0) - atoms.positions.min(axis=0)
        atoms.set_cell([max(float(v)+12.0, 15.0) for v in span])
        atoms.center(); atoms.pbc = True
        write(d/"molecule_padded_P1.cif", atoms)
        try: write(d/"molecule.gen", atoms, format="gen")
        except Exception: pass
        (d/"README.txt").write_text("Generated from SMILES with RDKit ETKDG and molecular mechanics. CIF uses an artificial padded P1 cell; it is not a crystal prediction. Check all structures before simulation.\n")
        bio = BytesIO()
        with zipfile.ZipFile(bio, "w", zipfile.ZIP_DEFLATED) as z:
            for f in d.iterdir(): z.write(f, f.name)
        bio.seek(0)
        from fastapi.responses import StreamingResponse
        return StreamingResponse(bio, media_type="application/zip", headers={"Content-Disposition":"attachment; filename=rdkit_ase_structure_package.zip"})


# --- Molecular design tools: descriptors and single-site substituent enumeration ---
from rdkit.Chem import Descriptors, Lipinski, Crippen, QED

class DescriptorRequest(BaseModel):
    smiles: str = Field(min_length=1, max_length=2000)

class EnumerationRequest(BaseModel):
    core_smiles: str = Field(min_length=1, max_length=1000)
    substituents: list[str] = Field(min_length=1, max_length=100)
    max_results: int = Field(default=100, ge=1, le=100)

def molecule_descriptors(smiles: str):
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        raise HTTPException(422, f"Invalid SMILES: {smiles}")
    canonical = Chem.MolToSmiles(mol, canonical=True)
    return {
        "smiles": canonical,
        "formula": rdMolDescriptors.CalcMolFormula(mol),
        "atom_count": mol.GetNumAtoms(),
        "formal_charge": int(Chem.GetFormalCharge(mol)),
        "molecular_weight": round(float(Descriptors.MolWt(mol)), 4),
        "exact_mass": round(float(Descriptors.ExactMolWt(mol)), 6),
        "logp": round(float(Crippen.MolLogP(mol)), 4),
        "tpsa": round(float(rdMolDescriptors.CalcTPSA(mol)), 4),
        "hbd": int(Lipinski.NumHDonors(mol)),
        "hba": int(Lipinski.NumHAcceptors(mol)),
        "rotatable_bonds": int(Lipinski.NumRotatableBonds(mol)),
        "rings": int(rdMolDescriptors.CalcNumRings(mol)),
        "fraction_csp3": round(float(rdMolDescriptors.CalcFractionCSP3(mol)), 4),
        "qed": round(float(QED.qed(mol)), 4),
    }

@app.post("/api/descriptors")
def descriptors(req: DescriptorRequest):
    return molecule_descriptors(req.smiles)

@app.post("/api/enumerate")
def enumerate_substituents(req: EnumerationRequest):
    core = Chem.MolFromSmiles(req.core_smiles)
    if core is None:
        raise HTTPException(422, "Core scaffold is not valid SMILES.")
    dummy = [a.GetIdx() for a in core.GetAtoms() if a.GetAtomicNum() == 0]
    if len(dummy) != 1:
        raise HTTPException(422, "Core scaffold must contain exactly one [*] attachment atom, e.g. c1cc([*])ccc1.")
    results, seen = [], set()
    errors = []
    for raw in req.substituents[:req.max_results]:
        s = raw.strip()
        if not s:
            continue
        sub = Chem.MolFromSmiles(s)
        if sub is None or any(a.GetAtomicNum() == 0 for a in sub.GetAtoms()):
            errors.append({"substituent": s, "error": "Use a valid substituent SMILES without [*]."})
            continue
        try:
            products = Chem.ReplaceSubstructs(core, Chem.MolFromSmarts("[*]"), sub, replaceAll=True)
            if not products:
                raise ValueError("Replacement did not produce a molecule.")
            product = products[0]
            Chem.SanitizeMol(product)
            smi = Chem.MolToSmiles(product, canonical=True)
            if smi in seen:
                continue
            seen.add(smi)
            row = molecule_descriptors(smi)
            row["substituent"] = s
            results.append(row)
        except Exception as exc:
            errors.append({"substituent": s, "error": str(exc)})
    return {"core_smiles": Chem.MolToSmiles(core, canonical=True), "count": len(results), "results": results, "errors": errors}
